// 訪客沙盒的補建（issue #144）在 API 邊界上交換的資料形狀。
//
// 這一支的存在本身就是 #144 的主題：示範資料的複製要 11.5 秒，原本卡在 /auth/guest
// 的 302 之前，訪客只能對著登入頁乾等。移出來之後由首頁在畫面已經看得到之後才呼叫，
// 等待因此發生在「使用者看得到有事情正在進行」的地方。

export interface GuestSandboxResponse {
  /** 這一次複製了幾個缸。已經備妥時是 0。 */
  copied: number
  /**
   * 這一次什麼都沒做，因為沙盒早就備妥。
   *
   * 首頁用它分辨兩件在畫面上長得一樣、但意思完全相反的事：
   * `false` ＝ 剛剛才把示範資料放進來，該重新取一次；
   * `true` 而且名下仍然沒有缸 ＝ 這個帳號真的沒有缸（例如 Google 使用者），
   * 該顯示「還沒有任何缸」的空狀態，而不是繼續等。
   */
  alreadySeeded: boolean
}
